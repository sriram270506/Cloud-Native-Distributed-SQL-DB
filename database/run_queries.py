"""Build the e-commerce database in SQLite and run every documented query.

Usage:  python database/run_queries.py [--db database/ecommerce.db]
Writes the results of each query in queries.sql to database/results/query_results.md.
"""
import argparse
import re
import sqlite3
from pathlib import Path

HERE = Path(__file__).resolve().parent


def build(connection: sqlite3.Connection) -> None:
    connection.executescript((HERE / "schema.sql").read_text())
    connection.executescript((HERE / "seed.sql").read_text())


def parse_queries(text: str):
    """Split queries.sql into (id, title, purpose, sql) on the '-- @Qn' markers."""
    blocks = re.split(r"^-- @(Q\d+) ", text, flags=re.M)[1:]
    for qid, body in zip(blocks[::2], blocks[1::2]):
        lines = body.strip().splitlines()
        title = lines[0].strip()
        purpose = next((l[len("-- Purpose:"):].strip() for l in lines if l.startswith("-- Purpose:")), "")
        sql = "\n".join(l for l in lines[1:] if not l.startswith("--")).strip()
        yield qid, title, purpose, sql


def markdown_table(columns, rows) -> str:
    if not rows:
        return "_No rows._\n"
    out = ["| " + " | ".join(columns) + " |", "|" + "---|" * len(columns)]
    out += ["| " + " | ".join("" if v is None else str(v) for v in row) + " |" for row in rows]
    return "\n".join(out) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--db", default=":memory:", help="SQLite file to create (default: in memory)")
    args = parser.parse_args()
    if args.db != ":memory:":
        Path(args.db).unlink(missing_ok=True)
    connection = sqlite3.connect(args.db)
    build(connection)

    report = ["# Query results\n",
              f"Generated by `python database/run_queries.py` on SQLite {sqlite3.sqlite_version} "
              "from `schema.sql`, `seed.sql` and `queries.sql`.\n"]
    for qid, title, purpose, sql in parse_queries((HERE / "queries.sql").read_text()):
        cursor = connection.execute(sql)
        columns = [d[0] for d in cursor.description]
        rows = cursor.fetchall()
        report += [f"## {qid}. {title}\n", f"{purpose}\n", f"```sql\n{sql}\n```\n",
                   f"{len(rows)} row(s):\n", markdown_table(columns, rows)]
        print(f"{qid}: {len(rows)} row(s) - {title}")
    connection.commit()
    out = HERE / "results" / "query_results.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(report), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
