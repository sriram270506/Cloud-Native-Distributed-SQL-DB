"""Create and populate the supermarket tables in the running Raft cluster, then run demo queries.

Start a cluster first (scripts/cluster.ps1, scripts/cluster.sh or docker compose up), then:
    python database/seed_cluster.py [--url http://localhost:8080]

Every table is created and filled in one /transaction call, so it commits atomically through Raft.
Values are sent as bound parameters (? placeholders), never spliced into SQL text.
Results are written to database/results/cluster_demo.md.
"""
import argparse
import csv
import json
import time
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLES = ["customers", "addresses", "products", "orders", "order_items", "payments"]

# Queries in the SQL subset the distributed engine supports (see README "Supported SQL").
DEMO_QUERIES = [
    ("Point lookup with a bound parameter", "SELECT customer_id, first_name, last_name, email FROM customers WHERE email = ?", ["ava.jones@example.com"]),
    ("Injection attempt is treated as data (0 rows)", "SELECT * FROM customers WHERE email = ?", ["x' OR '1'='1"]),
    ("Join: orders with customer names", "SELECT orders.order_id, customers.first_name, orders.total_amount FROM orders JOIN customers ON orders.customer_id = customers.customer_id ORDER BY order_id", []),
    ("GROUP BY with COUNT and AVG", "SELECT category, COUNT(*) AS products, AVG(unit_price) AS avg_price FROM products GROUP BY category ORDER BY category", []),
    ("GROUP BY ... HAVING", "SELECT method, COUNT(*) AS payments, SUM(amount) AS total FROM payments GROUP BY method HAVING payments > 1", []),
    ("Filter with OR, ORDER BY and LIMIT", "SELECT product_name, unit_price, stock_qty FROM products WHERE category = ? OR stock_qty < ? ORDER BY unit_price DESC LIMIT 5", ["tools", 30]),
]


def call(url, path, payload=None):
    data = None if payload is None else json.dumps(payload).encode()
    request = urllib.request.Request(url + path, data=data, headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            return json.loads(response.read() or b"null")
    except urllib.error.HTTPError as error:
        raise SystemExit(f"{path} failed ({error.code}): {error.read().decode().strip()}")


def wait_for_leader(url, timeout=30):
    deadline = time.time() + timeout
    while time.time() < deadline:
        try:
            with urllib.request.urlopen(url + "/ready", timeout=3):
                return
        except OSError:
            time.sleep(0.5)
    raise SystemExit(f"no Raft leader at {url} after {timeout}s")


def seed(url):
    existing = set(call(url, "/tables")["tables"])
    for table in TABLES:
        if table in existing:
            print(f"{table}: already exists, skipped")
            continue
        with open(ROOT / "data" / "sample_db" / f"{table}.csv", newline="") as handle:
            rows = list(csv.DictReader(handle))
        columns = list(rows[0].keys())
        statements = [f"CREATE TABLE {table} ({', '.join(c + ' TEXT' for c in columns)})"]
        params = [[]]
        insert = f"INSERT INTO {table} ({', '.join(columns)}) VALUES ({', '.join('?' for _ in columns)})"
        for row in rows:
            statements.append(insert)
            params.append([row[c] for c in columns])
        call(url, "/transaction", {"statements": statements, "statement_params": params})
        print(f"{table}: created with {len(rows)} rows")


def demo(url):
    lines = ["# Distributed cluster demo\n",
             "Generated by `python database/seed_cluster.py` against a live three-node Raft cluster.\n"]
    health = call(url, "/health")
    lines.append(f"Node `{health['id']}` reports state **{health['state']}**, leader `{health['leader_id']}`, "
                 f"term {health['term']}, commit index {health['commit_index']}.\n")
    for title, sql, params in DEMO_QUERIES:
        result = call(url, "/query", {"sql": sql, "params": params})
        rows = result.get("rows") or []
        columns = result.get("columns") or []
        lines += [f"## {title}\n", f"```sql\n{sql}\n```\n"]
        if params:
            lines.append(f"Parameters: `{json.dumps(params)}`\n")
        if rows:
            lines.append("| " + " | ".join(columns) + " |")
            lines.append("|" + "---|" * len(columns))
            lines += ["| " + " | ".join(str(row.get(c, "")) for c in columns) + " |" for row in rows]
            lines.append("")
        else:
            lines.append("_No rows._\n")
        print(f"{title}: {len(rows)} row(s)")
    out = ROOT / "database" / "results" / "cluster_demo.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out}")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--url", default="http://localhost:8080")
    args = parser.parse_args()
    wait_for_leader(args.url)
    seed(args.url)
    demo(args.url)


if __name__ == "__main__":
    main()
